//                         loops in c
/*
definition :-a loop is a control flow statement used to execute a block of code repeatedly as long as a specified condition remains true. Loops help automate repetitive tasks without writing redundant code.

key advantages of loops:
1. code reusability
2. save time & effort
3. traversing data

types of loops in c

//                 1.for Loop

.Used when the exact number of iterations is known in advance.

Syntax:


for (initialization; condition; increment/decrement) {
    // Code to execute
}


//                   2.while Loop

.An entry-controlled loop that checks the condition before executing the loop body. If the condition is false initially, the loop body does not run.

Syntax:

while (condition) {
    // Code to execute
    // Increment or decrement
}


//             3.do-while Loop

.An exit-controlled loop that checks the condition after executing the loop body, ensuring the code runs at least once even if the condition is false.

Syntax:

do {
    // Code to execute
    // Increment or decrement
} while (condition);

*/